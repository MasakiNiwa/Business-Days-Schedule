function renderSection(section: Section): HTMLElement {
  const element = h(
    'section',
    { class: 'editor-section help-section', id: `help-${section.id}` },
    h('h3', { class: 'editor-heading' }, section.title),
  );
  if (section.lead !== undefined) {
    element.append(h('p', { class: 'field-hint' }, section.lead));
  }
  if (section.steps !== undefined) {
    element.append(
      h('ol', { class: 'help-steps' }, ...section.steps.map((step) => h('li', {}, step))),
    );
  }
  if (section.rows !== undefined) {
    element.append(
      h(
        'dl',
        { class: 'help-list' },
        ...section.rows.flatMap((row) => [h('dt', {}, row.term), h('dd', {}, row.body)]),
      ),
    );
  }
  for (const note of section.notes ?? []) {
    element.append(h('p', { class: 'help-note' }, note));
  }
  return element;
}

export function renderHelp(onClose: () => void): HTMLElement {
  const root = h(
    'section',
    { class: 'help' },
    h('h2', { class: 'editor-title' }, 'ヘルプ'),
  );

  // 長いので、まず行き先を並べる。読みたいところへ直接飛べるようにする。
  const toc = h('nav', { class: 'help-toc', 'aria-label': 'ヘルプの目次' });
  for (const section of SECTIONS) {
    const link = h('a', { href: `#help-${section.id}`, class: 'help-toc-link' }, section.title);
    link.addEventListener('click', (event) => {
      // モーダルの中では通常のアンカー移動が効かないため、自分で送る。
      event.preventDefault();
      root.querySelector(`#help-${section.id}`)?.scrollIntoView({ block: 'start' });
    });
    toc.append(link);
  }
  root.append(toc);

  for (const section of SECTIONS) root.append(renderSection(section));

  root.append(h('div', { class: 'editor-actions' }, button('閉じる', onClose, 'button button-primary')));
  return root;
}
